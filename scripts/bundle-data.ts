import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { z } from 'zod';
import { euSchema } from './eu-smpc';

async function main() {
  const root = process.cwd();
  const output = path.join(root, 'server/generated');
  await mkdir(output, { recursive: true });
  const catalog = JSON.parse(await readFile(path.join(root, 'data/catalog.json'), 'utf8'));
  await writeFile(path.join(output, 'catalog.ts'), `// Generated by npm run bundle:data. Do not edit.\nimport type { CatalogEntry } from '../../shared/contract';\nexport const catalog: CatalogEntry[] = ${JSON.stringify(catalog)};\n`);
  const evidence: Record<string, unknown> = {};
  for (const name of (await readdir(path.join(root, 'data/evidence'))).sort()) {
    if (!name.endsWith('.json')) continue;
    const record = JSON.parse(await readFile(path.join(root, 'data/evidence', name), 'utf8'));
    // Keep the public record and replay trace, omit precompute-only accounting.
    evidence[name.slice(0, -5)] = { card: record.card, trace: record.trace };
  }
  const schema = z.object({ kind: z.enum(['fda_label', 'pubmed', 'eu_smpc']), id: z.string(), text: z.string() });
  const sources: Record<string, z.infer<typeof schema>> = {};
  for (const kind of ['fda_label', 'pubmed']) {
    for (const name of (await readdir(path.join(root, 'data/sources', kind))).sort()) {
      if (!name.endsWith('.json')) continue;
      const snapshot = schema.parse(JSON.parse(await readFile(path.join(root, 'data/sources', kind, name), 'utf8')));
      if (snapshot.kind !== kind || sources[snapshot.id]) throw new Error(`Duplicate or invalid source: ${name}`);
      sources[snapshot.id] = snapshot;
    }
  }
  for (const country of ['ES', 'FR', 'EU']) {
    const directory = path.join(root, 'data/sources/eu', country);
    for (const name of (await readdir(directory).catch(() => [] as string[])).sort()) {
      if (!name.endsWith('.json')) continue;
      const snapshot = euSchema.parse(JSON.parse(await readFile(path.join(directory, name), 'utf8')));
      if (snapshot.country !== country) throw new Error(`EU country mismatch: ${name}`);
      for (const section of snapshot.sections) {
        const id = `${country}:${snapshot.registryId}#${section.section}`;
        if (sources[id] && sources[id].text !== section.text) throw new Error(`Conflicting EU source: ${id}`);
        sources[id] = { kind: 'eu_smpc', id, text: section.text };
      }
    }
  }
  await writeFile(path.join(output, 'evidence.ts'), `// Generated by npm run bundle:data. Do not edit.\nimport type { EvidenceRecord } from '../../shared/contract';\nexport const evidence: Record<string, EvidenceRecord | undefined> = ${JSON.stringify(evidence)};\n`);
  await writeFile(path.join(output, 'sources.ts'), `// Generated by npm run bundle:data. Do not edit.\nimport type { SourceRef } from '../../shared/contract';\nexport const sources: Record<string, (SourceRef & { text: string }) | undefined> = ${JSON.stringify(sources)};\n`);
  // Agent-built cards (origin "batch"/"requested"), served only for pairs that are not curated.
  const batchDir = path.join(root, 'data/batch/evidence');
  const batch: Record<string, unknown> = {};
  // Cards an audit found off-topic (e.g. alcohol as an ingredient, not a drink); reasons in the file.
  const excluded = JSON.parse(await readFile(path.join(root, 'data/batch/excluded.json'), 'utf8').catch(() => '{}')) as Record<string, string>;
  for (const name of (await readdir(batchDir).catch(() => [] as string[])).sort()) {
    if (!name.endsWith('.json')) continue;
    const key = name.slice(0, -5);
    if (evidence[key]) continue; // curated wins
    if (excluded[key]) continue;
    const record = JSON.parse(await readFile(path.join(batchDir, name), 'utf8'));
    batch[key] = { card: record.card, trace: record.trace ?? [] };
  }
  const index = JSON.parse(await readFile(path.join(root, 'data/batch/index.json'), 'utf8').catch(() => '[]')) as { pair: string }[];
  const rows = index.filter((row) => batch[row.pair]);
  await writeFile(path.join(output, 'batch.ts'), `// Generated by npm run bundle:data. Do not edit.
import type { BatchIndexRow, EvidenceRecord } from '../../shared/contract';
export const batchEvidence: Record<string, EvidenceRecord | undefined> = ${JSON.stringify(batch)};
export const batchIndex: BatchIndexRow[] = ${JSON.stringify(rows)};
`);
  console.info(`Bundled ${Object.keys(evidence).length} evidence records, ${Object.keys(batch).length} agent-built cards and ${Object.keys(sources).length} sources.`);
}
main().catch(error => { console.error(error); process.exitCode = 1; });
